#!/usr/bin/env bun
/**
 * Local seed / zero-data-loss importer from a legacy Tabquest SQLite/Turso
 * snapshot into Wrangler D1 (local by default).
 *
 * Usage:
 *   bun run scripts/seed-from-turso.ts [--source <path>] [--remote] [--sql-only <out.sql>]
 *
 * Guarantees:
 * - Preserves all 10 legacy tables with exact IDs, public_id, image_object_key,
 *   split_version (1 for historical published bills when absent in source),
 *   rounding_bill_player_id, paid_amount, and payment_events.
 * - Verifies exact row counts and rupiah sums between source SQLite and target D1.
 * - Verifies `PRAGMA foreign_key_check` returns 0 violations on target D1.
 */
import { Database as SqliteDatabase } from "bun:sqlite"
import { spawnSync } from "node:child_process"
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"

import { computeSplit } from "../src/domain/split"
import type { SplitVersion } from "../src/domain/split"

const DEFAULT_SOURCE = "./data/tabquest-turso.db"
const D1_DATABASE_NAME = "tabquest-db"

interface TableMetrics {
  table: string
  rows: number
  sum: number
}

const LEGACY_TABLES = [
  "players",
  "bills",
  "player_hover_summaries",
  "bill_players",
  "items",
  "item_allocations",
  "adjustments",
  "adjustment_allocations",
  "payment_statuses",
  "payment_events",
] as const

const VERIFY_QUERIES = [
  "SELECT 'bills' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(final_total), 0) AS total FROM bills;",
  "SELECT 'bills_subtotal' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(source_subtotal), 0) AS total FROM bills;",
  "SELECT 'players' AS tbl, COUNT(*) AS cnt, 0 AS total FROM players;",
  "SELECT 'player_hover_summaries' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(total_spend), 0) AS total FROM player_hover_summaries;",
  "SELECT 'bill_players' AS tbl, COUNT(*) AS cnt, 0 AS total FROM bill_players;",
  "SELECT 'items' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(line_total), 0) AS total FROM items;",
  "SELECT 'item_allocations' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(quantity), 0) AS total FROM item_allocations;",
  "SELECT 'adjustments' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(signed_amount), 0) AS total FROM adjustments;",
  "SELECT 'adjustment_allocations' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(signed_amount), 0) AS total FROM adjustment_allocations;",
  "SELECT 'payment_statuses' AS tbl, COUNT(*) AS cnt, COALESCE(SUM(paid_amount), 0) AS total FROM payment_statuses;",
  "SELECT 'payment_events' AS tbl, COUNT(*) AS cnt, 0 AS total FROM payment_events;",
] as const

function parseArgs(argv: string[]) {
  let source = DEFAULT_SOURCE
  let remote = false
  let sqlOnly: string | null = null

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === "--source" && argv[i + 1]) {
      source = argv[i + 1]
      i += 1
    } else if (arg === "--remote") {
      remote = true
    } else if (arg === "--sql-only" && argv[i + 1]) {
      sqlOnly = argv[i + 1]
      i += 1
    } else if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: bun run scripts/seed-from-turso.ts [--source <path>] [--remote] [--sql-only <out.sql>]"
      )
      process.exit(0)
    }
  }
  return { source, remote, sqlOnly }
}

function sqlLiteral(value: unknown): string {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Non-finite number: ${value}`)
    return String(value)
  }
  if (typeof value === "boolean") return value ? "1" : "0"
  if (typeof value === "string") {
    return `'${value.replaceAll("'", "''")}'`
  }
  throw new Error(`Unsupported SQL value type: ${typeof value}`)
}

function tableColumns(db: SqliteDatabase, table: string): Set<string> {
  const rows = db
    .query<{ name: string }, []>(`PRAGMA table_info("${table}")`)
    .all()
  return new Set(rows.map((r) => r.name))
}

function buildImportSql(sourceDb: SqliteDatabase): string {
  const lines: string[] = [
    "-- Generated by scripts/seed-from-turso.ts",
    "-- Idempotent import of all 10 legacy Tabquest tables into Cloudflare D1.",
    "",
  ]

  // Clear child tables first (safe even with foreign_keys = ON), then insert parents first.
  // We delete in reverse dependency order so re-running the local seed is idempotent.
  const deleteOrder = [...LEGACY_TABLES].reverse()
  for (const table of deleteOrder) {
    lines.push(`DELETE FROM "${table}";`)
  }
  lines.push("")

  // 1. players
  const playerCols = tableColumns(sourceDb, "players")
  const hasTakesRounding = playerCols.has("takes_rounding")
  const players = sourceDb
    .query<Record<string, unknown>, []>("SELECT * FROM players ORDER BY id")
    .all()
  for (const row of players) {
    lines.push(
      `INSERT INTO "players" ("id", "name", "phone", "note", "archived_at", "takes_rounding", "user_id", "email", "avatar_object_key", "avatar_banned", "name_locked", "created_at", "updated_at") VALUES (${[
        row.id,
        row.name,
        row.phone ?? null,
        row.note ?? null,
        row.archived_at ?? null,
        hasTakesRounding ? (row.takes_rounding ?? 0) : 0,
        null,
        null,
        null,
        0,
        0,
        row.created_at,
        row.updated_at,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 2. bills
  const billCols = tableColumns(sourceDb, "bills")
  const hasSplitVersion = billCols.has("split_version")
  const hasRoundingBillPlayer = billCols.has("rounding_bill_player_id")
  const bills = sourceDb
    .query<Record<string, unknown>, []>("SELECT * FROM bills ORDER BY id")
    .all()
  for (const row of bills) {
    // Historical published bills before commit 5111f78 used split_version = 1.
    const splitVersion = hasSplitVersion
      ? (row.split_version ?? 2)
      : row.status === "published"
        ? 1
        : 2
    lines.push(
      `INSERT INTO "bills" ("id", "public_id", "merchant", "title", "order_date", "timezone", "currency", "source_subtotal", "final_total", "status", "image_object_key", "image_media_type", "image_byte_size", "created_at", "updated_at", "published_at", "archived_at", "split_version", "rounding_bill_player_id") VALUES (${[
        row.id,
        row.public_id,
        row.merchant,
        row.title ?? null,
        row.order_date,
        row.timezone ?? "Asia/Jakarta",
        row.currency ?? "IDR",
        row.source_subtotal,
        row.final_total,
        row.status ?? "draft",
        row.image_object_key ?? null,
        row.image_media_type ?? null,
        row.image_byte_size ?? null,
        row.created_at,
        row.updated_at,
        row.published_at ?? null,
        row.archived_at ?? null,
        splitVersion,
        hasRoundingBillPlayer ? (row.rounding_bill_player_id ?? null) : null,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 3. player_hover_summaries
  const summaries = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM player_hover_summaries ORDER BY player_id"
    )
    .all()
  for (const row of summaries) {
    lines.push(
      `INSERT INTO "player_hover_summaries" ("player_id", "rank", "total_spend", "total_tips", "order_count", "badges_json") VALUES (${[
        row.player_id,
        row.rank,
        row.total_spend,
        row.total_tips,
        row.order_count,
        row.badges_json,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 4. bill_players (with denormalized split snapshot computed via src/domain/split.ts)
  const billPlayers = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM bill_players ORDER BY id"
    )
    .all()
  const itemCols = tableColumns(sourceDb, "items")
  const hasBundleSize = itemCols.has("bundle_size")
  const items = sourceDb
    .query<Record<string, unknown>, []>("SELECT * FROM items ORDER BY id")
    .all()
  const itemAllocations = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM item_allocations ORDER BY id"
    )
    .all()
  const adjCols = tableColumns(sourceDb, "adjustments")
  const hasOriginalAmount = adjCols.has("original_amount")
  const adjustments = sourceDb
    .query<Record<string, unknown>, []>("SELECT * FROM adjustments ORDER BY id")
    .all()

  const shareByBillPlayerId = new Map<
    string,
    { itemSubtotal: number; adjustmentTotal: number; shareAmount: number }
  >()

  for (const bill of bills) {
    const billId = String(bill.id)
    const bps = billPlayers
      .filter((bp) => String(bp.bill_id) === billId)
      .sort((a, b) => Number(a.sort_order) - Number(b.sort_order))
    const billItems = items
      .filter((it) => String(it.bill_id) === billId)
      .sort((a, b) => Number(a.sort_order) - Number(b.sort_order))
    const itemIdSet = new Set(billItems.map((it) => String(it.id)))
    const billAllocs = itemAllocations.filter((al) =>
      itemIdSet.has(String(al.item_id))
    )
    const billAdjs = adjustments
      .filter((ad) => String(ad.bill_id) === billId)
      .sort((a, b) => Number(a.sort_order) - Number(b.sort_order))

    const splitVersion: SplitVersion = hasSplitVersion
      ? Number(bill.split_version ?? 2) === 1
        ? 1
        : 2
      : bill.status === "published"
        ? 1
        : 2

    try {
      const split = computeSplit({
        items: billItems.map((it) => ({
          id: String(it.id),
          name: String(it.name),
          quantity: Number(it.quantity),
          unitPrice: Number(it.unit_price),
          bundleSize: hasBundleSize ? Number(it.bundle_size ?? 1) : 1,
          lineTotal: Number(it.line_total),
        })),
        billPlayers: bps.map((bp) => ({ id: String(bp.id) })),
        allocations: billAllocs.map((al) => ({
          itemId: String(al.item_id),
          billPlayerId: String(al.bill_player_id),
          quantity: Number(al.quantity),
        })),
        adjustments: billAdjs.map((ad) => ({
          id: String(ad.id),
          type: String(ad.type),
          amount: Number(ad.signed_amount),
        })),
        sourceSubtotal: Number(bill.source_subtotal),
        finalTotal: Number(bill.final_total),
        splitVersion,
        roundingBillPlayerId:
          hasRoundingBillPlayer && bill.rounding_bill_player_id
            ? String(bill.rounding_bill_player_id)
            : undefined,
      })
      for (const share of split.shares) {
        shareByBillPlayerId.set(share.billPlayerId, {
          itemSubtotal: share.itemSubtotal,
          adjustmentTotal: share.total - share.itemSubtotal,
          shareAmount: share.total,
        })
      }
    } catch (error) {
      if (bill.status === "published") {
        throw new Error(
          `Failed to compute split for published bill ${billId} (${bill.merchant}): ${String(error)}`
        )
      }
      // Incomplete drafts may not pass full split validation yet; leave 0.
    }
  }

  for (const row of billPlayers) {
    const computed = shareByBillPlayerId.get(String(row.id)) ?? {
      itemSubtotal: 0,
      adjustmentTotal: 0,
      shareAmount: 0,
    }
    lines.push(
      `INSERT INTO "bill_players" ("id", "bill_id", "alias", "sort_order", "player_id", "item_subtotal", "adjustment_total", "share_amount") VALUES (${[
        row.id,
        row.bill_id,
        row.alias,
        row.sort_order,
        row.player_id ?? null,
        computed.itemSubtotal,
        computed.adjustmentTotal,
        computed.shareAmount,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 5. items
  for (const row of items) {
    lines.push(
      `INSERT INTO "items" ("id", "bill_id", "name", "variant_notes", "quantity", "unit_price", "line_total", "bundle_size", "sort_order") VALUES (${[
        row.id,
        row.bill_id,
        row.name,
        row.variant_notes ?? null,
        row.quantity,
        row.unit_price,
        row.line_total,
        hasBundleSize ? (row.bundle_size ?? 1) : 1,
        row.sort_order,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 6. item_allocations
  for (const row of itemAllocations) {
    lines.push(
      `INSERT INTO "item_allocations" ("id", "item_id", "bill_player_id", "quantity") VALUES (${[
        row.id,
        row.item_id,
        row.bill_player_id,
        row.quantity,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 7. adjustments
  for (const row of adjustments) {
    lines.push(
      `INSERT INTO "adjustments" ("id", "bill_id", "type", "label", "signed_amount", "original_amount", "sort_order") VALUES (${[
        row.id,
        row.bill_id,
        row.type,
        row.label,
        row.signed_amount,
        hasOriginalAmount ? (row.original_amount ?? null) : null,
        row.sort_order,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 8. adjustment_allocations
  const adjAllocations = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM adjustment_allocations ORDER BY id"
    )
    .all()
  for (const row of adjAllocations) {
    lines.push(
      `INSERT INTO "adjustment_allocations" ("id", "adjustment_id", "bill_player_id", "signed_amount") VALUES (${[
        row.id,
        row.adjustment_id,
        row.bill_player_id,
        row.signed_amount,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 9. payment_statuses
  const paymentStatuses = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM payment_statuses ORDER BY bill_player_id"
    )
    .all()
  for (const row of paymentStatuses) {
    lines.push(
      `INSERT INTO "payment_statuses" ("bill_player_id", "status", "paid_amount", "paid_at", "last_changed_by", "updated_at") VALUES (${[
        row.bill_player_id,
        row.status ?? "unpaid",
        row.paid_amount ?? null,
        row.paid_at ?? null,
        row.last_changed_by ?? null,
        row.updated_at,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // 10. payment_events
  const paymentEvents = sourceDb
    .query<Record<string, unknown>, []>(
      "SELECT * FROM payment_events ORDER BY id"
    )
    .all()
  for (const row of paymentEvents) {
    lines.push(
      `INSERT INTO "payment_events" ("id", "bill_player_id", "previous_state", "new_state", "actor_identity", "event_time") VALUES (${[
        row.id,
        row.bill_player_id,
        row.previous_state,
        row.new_state,
        row.actor_identity,
        row.event_time,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    )
  }
  lines.push("")

  // Ensure singleton app_settings row exists without overwriting existing config.
  const nowIso = new Date().toISOString()
  lines.push(
    `INSERT OR IGNORE INTO "app_settings" ("id", "app_name", "tagline", "icon_url", "payment_methods_json", "updated_at", "updated_by") VALUES ('default', NULL, NULL, NULL, '[]', ${sqlLiteral(nowIso)}, 'seed-from-turso');`
  )
  lines.push("")

  return lines.join("\n")
}

function readSourceMetrics(sourceDb: SqliteDatabase): TableMetrics[] {
  return VERIFY_QUERIES.map((sql) => {
    const row = sourceDb
      .query<{ tbl: string; cnt: number; total: number }, []>(sql)
      .get()
    if (!row) throw new Error(`No verification row returned for: ${sql}`)
    return {
      table: row.tbl,
      rows: Number(row.cnt),
      sum: Number(row.total),
    }
  })
}

function runWranglerD1(args: string[]): string {
  const result = spawnSync("bunx", ["wrangler", "d1", ...args], {
    encoding: "utf8",
    env: { ...process.env, CI: "true" },
    stdio: ["ignore", "pipe", "pipe"],
  })
  if (result.status !== 0) {
    throw new Error(
      `wrangler d1 ${args.join(" ")} failed (exit ${result.status}):\n${result.stdout}\n${result.stderr}`
    )
  }
  return result.stdout
}

function parseWranglerJsonAllResults<T>(raw: string): T[] {
  const parsed = JSON.parse(raw) as Array<{ results?: T[] }>
  return parsed.flatMap((entry) => entry.results ?? [])
}

function main() {
  const { source, remote, sqlOnly } = parseArgs(process.argv.slice(2))
  if (!existsSync(source)) {
    console.error(`Source SQLite database not found: ${source}`)
    process.exit(1)
  }

  const sourceDb = new SqliteDatabase(source, { readonly: true })
  const sourceMetrics = readSourceMetrics(sourceDb)
  const importSql = buildImportSql(sourceDb)
  sourceDb.close()

  if (sqlOnly) {
    writeFileSync(sqlOnly, importSql, "utf8")
    console.log(`Wrote SQL import to ${sqlOnly}`)
    return
  }

  const targetFlag = remote ? "--remote" : "--local"
  const tempDir = mkdtempSync(path.join(tmpdir(), "tabquest-seed-"))
  const sqlFile = path.join(tempDir, "import.sql")

  try {
    writeFileSync(sqlFile, importSql, "utf8")
    console.log(
      `Importing legacy snapshot (${source}) into D1 (${D1_DATABASE_NAME} ${targetFlag})...`
    )
    runWranglerD1([
      "execute",
      D1_DATABASE_NAME,
      targetFlag,
      "--file",
      sqlFile,
    ])

    const verifyRaw = runWranglerD1([
      "execute",
      D1_DATABASE_NAME,
      targetFlag,
      "--json",
      "--command",
      VERIFY_QUERIES.join(" "),
    ])
    const targetMetrics = parseWranglerJsonAllResults<{
      tbl: string
      cnt: number
      total: number
    }>(verifyRaw).map((r) => ({
      table: r.tbl,
      rows: Number(r.cnt),
      sum: Number(r.total),
    }))

    const shareSumRaw = runWranglerD1([
      "execute",
      D1_DATABASE_NAME,
      targetFlag,
      "--json",
      "--command",
      "SELECT COALESCE(SUM(bp.share_amount), 0) AS shares_sum, COALESCE((SELECT SUM(final_total) FROM bills WHERE status = 'published'), 0) AS bills_sum FROM bill_players bp JOIN bills b ON b.id = bp.bill_id WHERE b.status = 'published';",
    ])
    const shareCheck = parseWranglerJsonAllResults<{
      shares_sum: number
      bills_sum: number
    }>(shareSumRaw)[0]

    const fkRaw = runWranglerD1([
      "execute",
      D1_DATABASE_NAME,
      targetFlag,
      "--json",
      "--command",
      "PRAGMA foreign_key_check;",
    ])
    const fkViolations = parseWranglerJsonAllResults<Record<string, unknown>>(
      fkRaw
    )

    let mismatches = 0
    console.log("\nVerification summary (source vs D1 target):")
    console.log(
      "table".padEnd(26) +
        "src_rows".padStart(10) +
        "dst_rows".padStart(10) +
        "src_sum".padStart(14) +
        "dst_sum".padStart(14) +
        "  status"
    )
    for (const src of sourceMetrics) {
      const dst = targetMetrics.find((m) => m.table === src.table)
      const ok = dst !== undefined && dst.rows === src.rows && dst.sum === src.sum
      if (!ok) mismatches += 1
      console.log(
        src.table.padEnd(26) +
          String(src.rows).padStart(10) +
          String(dst?.rows ?? "MISSING").padStart(10) +
          String(src.sum).padStart(14) +
          String(dst?.sum ?? "MISSING").padStart(14) +
          (ok ? "  OK" : "  MISMATCH")
      )
    }

    if (
      !shareCheck ||
      Number(shareCheck.shares_sum) !== Number(shareCheck.bills_sum)
    ) {
      console.error(
        `\nPublished bill_players.share_amount sum (${shareCheck?.shares_sum}) != published bills.final_total sum (${shareCheck?.bills_sum})`
      )
      process.exit(1)
    }

    if (fkViolations.length > 0) {
      console.error(
        `\nPRAGMA foreign_key_check found ${fkViolations.length} violations:`,
        fkViolations
      )
      process.exit(1)
    }
    if (mismatches > 0) {
      console.error(`\nVerification failed with ${mismatches} mismatches.`)
      process.exit(1)
    }

    console.log(
      `\nPublished bill_players.share_amount sum = Rp${Number(shareCheck.shares_sum).toLocaleString("id-ID")} (matches published bills.final_total exactly).`
    )
    console.log("Zero-data-loss verification passed (0 mismatches, 0 FK violations).")
  } finally {
    rmSync(tempDir, { recursive: true, force: true })
  }
}

main()
